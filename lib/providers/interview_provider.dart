	static List<QuestionModel> _buildQuestions(
		String role,
		String type,
		String difficulty,
	) {
		final bankForRole = _staticQuestions[role];
		final bankForType = bankForRole?[type];
		final questions = bankForType?[difficulty];

		if (questions == null || questions.isEmpty) {
			return const [
				QuestionModel(
					id: 'fallback-1',
					text: 'Tell me about yourself.',
				),
				QuestionModel(
					id: 'fallback-2',
					text: 'Why should we hire you?',
				),
				QuestionModel(
					id: 'fallback-3',
					text: 'Describe a difficult situation you handled at work.',
				),
			];
		}

		return List<QuestionModel>.generate(
			questions.length,
			(index) => QuestionModel(
				id: 'static-${role.replaceAll(RegExp(r'\s+'), '-')}-${type.replaceAll(RegExp(r'\s+'), '-')}-${difficulty.toLowerCase()}-$index',
				text: questions[index],
			),
		);
	}

	final InterviewModel interview;
	final List<AnswerModel> answers = [];
	late DateTime _startedAt;
	int currentIndex = 0;
	bool isComplete = false;

	QuestionModel get currentQuestion => interview.questions[currentIndex];

	double get progress => (currentIndex + 1) / interview.questions.length;

	bool get isLastQuestion => currentIndex == interview.questions.length - 1;

	Duration get elapsed => DateTime.now().difference(_startedAt);

	void submitAnswer(String text, Duration duration) {
		final answer = AnswerModel(
			questionId: currentQuestion.id,
			text: text.trim(),
			duration: duration,
		);
		final existingIndex = answers.indexWhere(
			(item) => item.questionId == answer.questionId,
		);

		if (existingIndex == -1) {
			answers.add(answer);
		} else {
			answers[existingIndex] = answer;
		}
		notifyListeners();
	}

	void moveToNextQuestion() {
		if (isLastQuestion) {
			finish();
			return;
		}

		currentIndex++;
		notifyListeners();
	}

	void finish() {
		isComplete = true;
		notifyListeners();
	}
}
